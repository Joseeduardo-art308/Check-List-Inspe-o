create table if not exists public.historico_status_manutencao (
  id bigint generated always as identity primary key,
  solicitacao_manutencao_id uuid not null references public.solicitacoes_manutencao(id) on delete cascade,
  situacao_anterior text,
  situacao_nova text not null check (situacao_nova in ('aberta','em_manutencao','concluida')),
  alterado_por uuid references public.perfis(id) on delete set null,
  observacao_alteracao text,
  alterado_em timestamptz not null default now()
);
create or replace function public.registrar_alteracao_status_manutencao()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if tg_op = 'INSERT' then
    insert into public.historico_status_manutencao(solicitacao_manutencao_id,situacao_anterior,situacao_nova,alterado_por)
    values (new.id,null,new.situacao,(select auth.uid()));
  elsif new.situacao is distinct from old.situacao then
    insert into public.historico_status_manutencao(solicitacao_manutencao_id,situacao_anterior,situacao_nova,alterado_por)
    values (new.id,old.situacao,new.situacao,(select auth.uid()));
  end if;
  return new;
end;
$$;
drop trigger if exists maintenance_status_history_trigger on public.solicitacoes_manutencao;
create trigger maintenance_status_history_trigger after insert or update of situacao
on public.solicitacoes_manutencao for each row execute procedure public.registrar_alteracao_status_manutencao();

