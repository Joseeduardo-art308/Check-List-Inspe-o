create extension if not exists pgcrypto with schema extensions;

-- Supabase Auth guarda credenciais; esta tabela guarda dados de perfil/permissão.
create table if not exists public.perfis (
  id uuid primary key references auth.users(id) on delete cascade,
  nome_usuario text not null,
  nome_exibicao text not null,
  perfil_acesso text not null default 'motorista'
    check (perfil_acesso in ('administrador','supervisor','operador','motorista','responsavel_manutencao')),
  ativo boolean not null default true,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  check (length(btrim(nome_usuario)) > 0),
  check (length(btrim(nome_exibicao)) > 0)
);
create unique index if not exists profiles_username_lower_idx on public.perfis (lower(nome_usuario));

create or replace function public.perfil_atual_usuario()
returns text language sql stable security definer set search_path = '' as $$
  select p.perfil_acesso from public.perfis p
  where p.id = (select auth.uid()) and p.ativo = true limit 1;
$$;

create or replace function public.usuario_eh_admin_ou_supervisor()
returns boolean language sql stable security definer set search_path = '' as $$
  select coalesce(public.perfil_atual_usuario() in ('administrador','supervisor'), false);
$$;

-- No cadastro público, só motorista/operador podem ser escolhidos pelo usuário.
create or replace function public.criar_perfil_novo_usuario()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  requested_role text;
  requested_username text;
  requested_name text;
begin
  requested_role := lower(coalesce(new.raw_user_meta_data ->> 'role', 'motorista'));
  if requested_role not in ('motorista','operador') then requested_role := 'motorista'; end if;
  requested_username := nullif(btrim(new.raw_user_meta_data ->> 'username'), '');
  requested_name := nullif(btrim(new.raw_user_meta_data ->> 'display_name'), '');
  insert into public.perfis (id, nome_usuario, nome_exibicao, perfil_acesso)
  values (
    new.id,
    coalesce(requested_username, split_part(coalesce(new.email,new.phone,new.id::text), '@', 1)),
    coalesce(requested_name, requested_username, split_part(coalesce(new.email,new.phone,'Usuário'), '@', 1)),
    requested_role
  );
  return new;
end;
$$;
drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile after insert on auth.users
for each row execute procedure public.criar_perfil_novo_usuario();

create or replace function public.impedir_alteracao_perfil_nao_autorizada()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if (new.perfil_acesso is distinct from old.perfil_acesso or new.ativo is distinct from old.ativo)
     and (select auth.uid()) is not null
     and not public.usuario_eh_admin_ou_supervisor() then
    raise exception 'Somente administrador ou supervisor pode alterar o perfil.';
  end if;
  return new;
end;
$$;
drop trigger if exists profiles_guard_role_change on public.perfis;
create trigger profiles_guard_role_change before update on public.perfis
for each row execute procedure public.impedir_alteracao_perfil_nao_autorizada();

create or replace function public.atualizar_data_modificacao()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.atualizado_em := now();
  return new;
end;
$$;
drop trigger if exists profiles_touch_updated_at on public.perfis;
create trigger profiles_touch_updated_at before update on public.perfis
for each row execute procedure public.atualizar_data_modificacao();

